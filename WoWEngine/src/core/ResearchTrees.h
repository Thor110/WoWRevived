// come from OBJ.ojd). Generated from the constructors' calls, in their order: AddTrigger 0x458950, AddPlan
// 0x458670 (the plan's name text), AddPage 0x4586E0 (its number), AddUnit 0x458890 / AddBuilding 0x4588F0 /
// AddEnhancement 0x458830 (the unit type and up to four prerequisites, as indices of the items made before it;
// -1 for none, the first is the one 0x45BB90 may make obsolete). Items are numbered in the order they're made,
// triggers first: that number (+0x20) is what a save keeps for the current research.
