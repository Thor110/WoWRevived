#!/usr/bin/env python3
"""Bakes a TrueType font into the C++ header the installer draws its text with (src/launcher/UiFont.h).

    python3 bake_font.py <font.ttf> <pixel size> <out.h>

Needs ImageMagick's "convert". Each Latin-1 character (32-126, 160-255) is rendered on its own, antialiased,
and stored as 8-bit coverage. The installer ships DejaVu Sans (Bitstream Vera licence, free to embed).
"""
import subprocess, sys

def render(font, size, ch):
    text = ch.replace('\\', '\\\\')
    if ch == '%': text = '%%'
    args = ['convert', '-background', 'black', '-fill', 'white', '-font', font, '-pointsize', str(size), '-density', '72',
            'label:' + text]
    info = subprocess.run(args + ['-format', '%w %h', 'info:'], capture_output=True, text=True, check=True).stdout.split()
    w, h = int(info[0]), int(info[1])
    gray = subprocess.run(args + ['-depth', '8', 'gray:-'], capture_output=True, check=True).stdout
    return w, h, gray

def main(font, size, out):
    chars = [chr(c) for c in list(range(32, 127)) + list(range(160, 256))]
    glyphs = []
    height = None
    for ch in chars:
        w, h, gray = render(font, int(size), ch if ch != ' ' else '|')
        if ch == ' ':
            gray = bytes(len(gray)); w = max(3, w)
        height = h if height is None else height
        if h != height: raise SystemExit(f'glyph {ch!r} is {h} high, expected {height}')
        glyphs.append((ord(ch), w, gray))
    lines = ['// Generated by tools/bake_font.py from DejaVu Sans (Bitstream Vera licence) - do not edit.',
             '#pragma once', '#include <cstdint>', '', 'namespace wow::ui', '{',
             f'    constexpr int FontHeight = {height};',
             '    struct BakedGlyph { uint8_t code; uint8_t width; uint32_t offset; };',
             '    inline constexpr BakedGlyph FontGlyphs[] = {']
    offset = 0
    data = bytearray()
    for code, w, gray in glyphs:
        lines.append(f'        {{ {code}, {w}, {offset} }},')
        data += gray; offset += len(gray)
    lines += ['    };', '    inline constexpr uint8_t FontPixels[] = {']
    for i in range(0, len(data), 24):
        lines.append('        ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    lines += ['    };', '}', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print(f'{len(glyphs)} glyphs, height {height}, {len(data)} bytes')

if __name__ == '__main__':
    if len(sys.argv) != 4: sys.exit(__doc__)
    main(*sys.argv[1:])
